"""Render the dvfonts wordmark with text converted to outlines.

The Thaana is shaped with HarfBuzz (Bolhu Bold) and every glyph is emitted as a
path, so it renders identically everywhere without loading a font. Writes:

  .github/assets/banner-{light,dark}.svg      README title (stacked)
  apps/web/src/lib/components/logo.svelte     site header (one line, follows the theme)
  apps/web/src/lib/assets/favicon.svg         favicon

    uv run python scripts/readme_banner.py
"""

from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent  # fonts/
OUT = ROOT.parent / ".github" / "assets"
FONT = ROOT / "sources" / "bolhu-bold.ttf"
LATIN_FONT = ROOT / "sources" / "bolhu-bold.ttf"


def shape(path: Path, text: str, rtl: bool) -> tuple[list[tuple[str, float, float]], float, TTFont]:
    """Glyph names with pen positions (font units) and total advance."""
    data = path.read_bytes()
    face = hb.Face(data)
    font = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    if rtl:
        buf.direction, buf.script, buf.language = "rtl", "Thaa", "dv"
    hb.shape(font, buf)
    tt = TTFont(path)
    order = tt.getGlyphOrder()
    x = 0.0
    placed = []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions, strict=True):
        placed.append((order[info.codepoint], x + pos.x_offset, pos.y_offset))
        x += pos.x_advance
    return placed, x, tt


def path_for(tt: TTFont, placed, scale: float, ox: float, baseline: float) -> str:
    gs = tt.getGlyphSet()
    pen = SVGPathPen(gs)
    for name, gx, gy in placed:
        # Font units are y-up; SVG is y-down.
        t = TransformPen(pen, (scale, 0, 0, -scale, ox + gx * scale, baseline - gy * scale))
        gs[name].draw(t)
    return pen.getCommands()


def banner(fg: str, accent: str) -> str:
    latin, lw, ltt = shape(LATIN_FONT, "dvfonts", rtl=False)
    thaana, tw, ttt = shape(FONT, "ޑީވީފޮންޓްސް", rtl=True)
    lupm, tupm = ltt["head"].unitsPerEm, ttt["head"].unitsPerEm
    w = 1200
    ls, ts = 120 / lupm, 74 / tupm
    lx, tx = (w - lw * ls) / 2, (w - tw * ts) / 2
    label = "dvfonts — ޑީވީފޮންޓްސް"
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} 300" width="{w}" height="300"
  role="img" aria-label="{label}">
  <path fill="{fg}" d="{path_for(ltt, latin, ls, lx, 150)}"/>
  <path fill="{accent}" d="{path_for(ttt, thaana, ts, tx, 262)}"/>
</svg>
"""


def header_logo() -> str:
    """One-line wordmark for the site header; colours come from CSS."""
    latin, lw, ltt = shape(LATIN_FONT, "dvfonts", rtl=False)
    thaana, tw, ttt = shape(FONT, "ޑީވީފޮންޓްސް", rtl=True)
    h = 100
    ls, ts = 64 / ltt["head"].unitsPerEm, 44 / ttt["head"].unitsPerEm
    gap = 22
    width = lw * ls + gap + tw * ts
    latin_d = path_for(ltt, latin, ls, 0, 68)
    thaana_d = path_for(ttt, thaana, ts, lw * ls + gap, 66)
    return f"""<!-- Generated by fonts/scripts/readme_banner.py: dvfonts wordmark as outlines. -->
<script lang="ts">
	let {{ class: className = '' }}: {{ class?: string }} = $props();
</script>

<svg
	xmlns="http://www.w3.org/2000/svg"
	viewBox="0 0 {width:.0f} {h}"
	class={{className}}
	role="img"
	aria-label="dvfonts — ޑީވީފޮންޓްސް"
>
	<path fill="currentColor" d="{latin_d}" />
	<path class="fill-emerald-600 dark:fill-emerald-400" d="{thaana_d}" />
</svg>
"""


def favicon() -> str:
    """'dv' in Bolhu Bold, white on the accent green."""
    glyphs, w, tt = shape(LATIN_FONT, "dv", rtl=False)
    scale = 40 / tt["head"].unitsPerEm
    x = (64 - w * scale) / 2
    d = path_for(tt, glyphs, scale, x, 44)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="14" fill="#0e7c66"/>
  <path fill="#ffffff" d="{d}"/>
</svg>
"""


def main() -> None:
    web = ROOT.parent / "apps" / "web" / "src" / "lib"
    (web / "components" / "logo.svelte").write_text(header_logo())
    (web / "assets" / "favicon.svg").write_text(favicon())
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "banner-light.svg").write_text(banner("#0b0d12", "#0e7c66"))
    (OUT / "banner-dark.svg").write_text(banner("#f5f7fa", "#3ecfa9"))
    print(f"wrote {OUT / 'banner-light.svg'} and banner-dark.svg")


if __name__ == "__main__":
    main()
